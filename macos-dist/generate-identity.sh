#!/bin/bash
# Generate the identity constants compiled on both sides of Skylight's XPC boundary.
# Local builds pin a self-signed certificate SHA-1. Release builds pin Apple's
# generic anchor plus the Developer ID Team Identifier and exact bundle ID.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$DIR/.." && pwd)"
MODE="local"
IDENTITY=""
CPP_OUTPUT="$REPO/src/platform/macos/generated_identity.h"
SWIFT_OUTPUT="$DIR/SkylightMenu/Sources/SkylightMenu/GeneratedIdentity.swift"

while [ "$#" -gt 0 ]; do
  case "$1" in
    --mode) MODE="$2"; shift 2 ;;
    --identity) IDENTITY="$2"; shift 2 ;;
    --cpp-output) CPP_OUTPUT="$2"; shift 2 ;;
    --swift-output) SWIFT_OUTPUT="$2"; shift 2 ;;
    *) echo "ERROR: unknown argument: $1" >&2; exit 64 ;;
  esac
done
case "$MODE" in local|local-bundle|release) ;; *) echo "ERROR: --mode must be local, local-bundle or release" >&2; exit 64 ;; esac

source "$DIR/skylight-identity.conf"
[ "$MODE" != "release" ] && [ -f "$DIR/skylight-identity.local.conf" ] && source "$DIR/skylight-identity.local.conf"

if [ "$MODE" != "release" ]; then
  IDENTITY="${IDENTITY:-$SKYLIGHT_SIGNING_IDENTITY}"
  CERT_NAME="$IDENTITY" "$DIR/create-signing-cert.sh"
  CERT_SHA1=$(security find-certificate -c "$IDENTITY" -Z \
    "$HOME/Library/Keychains/login.keychain-db" 2>/dev/null | awk '/SHA-1 hash:/ {print tolower($3)}')
  [ -n "$CERT_SHA1" ] || { echo "ERROR: signing certificate '$IDENTITY' was not found" >&2; exit 1; }
  if [ "$MODE" = "local-bundle" ]; then
    MENU_BUNDLE_ID="$SKYLIGHT_BUNDLE_ID"
    HOST_BUNDLE_ID="$SKYLIGHT_HOST_BUNDLE_ID"
  else
    MENU_BUNDLE_ID="$SKYLIGHT_MENU_BUNDLE_ID"
    HOST_BUNDLE_ID="$SKYLIGHT_BUNDLE_ID"
  fi
  MENU_REQUIREMENT="identifier \"$MENU_BUNDLE_ID\" and certificate leaf = H\"$CERT_SHA1\""
  HOST_REQUIREMENT="identifier \"$HOST_BUNDLE_ID\" and certificate leaf = H\"$CERT_SHA1\""
  IDENTITY_NOTE="certificate=$IDENTITY sha1=$CERT_SHA1"
else
  [ -n "$IDENTITY" ] || { echo "ERROR: release mode requires --identity" >&2; exit 64; }
  # shellcheck source=../scripts/release/common.sh
  source "$REPO/scripts/release/common.sh"
  require_developer_id "$IDENTITY"
  TEAM_ID="$(release_team_id "$IDENTITY")"
  # The release menu is the outer app executable; the embedded host is a bare
  # helper with its own explicit signing identifier. Local builds retain the
  # legacy nested-menu identity to preserve existing TCC grants.
  MENU_REQUIREMENT="anchor apple generic and identifier \"$SKYLIGHT_BUNDLE_ID\" and certificate leaf[subject.OU] = \"$TEAM_ID\""
  HOST_REQUIREMENT="anchor apple generic and identifier \"$SKYLIGHT_HOST_BUNDLE_ID\" and certificate leaf[subject.OU] = \"$TEAM_ID\""
  IDENTITY_NOTE="identity=$IDENTITY team=$TEAM_ID"
fi

MENU_REQUIREMENT_CODE="$(printf '%s' "$MENU_REQUIREMENT" | sed 's/\\/\\\\/g; s/"/\\"/g')"
HOST_REQUIREMENT_CODE="$(printf '%s' "$HOST_REQUIREMENT" | sed 's/\\/\\\\/g; s/"/\\"/g')"

mkdir -p "$(dirname "$CPP_OUTPUT")" "$(dirname "$SWIFT_OUTPUT")"
cat > "$CPP_OUTPUT" <<H
// GENERATED by macos-dist/generate-identity.sh -- do not edit, do not commit.
// Mode: $MODE. Values: skylight-identity.conf (+ .local.conf).
#pragma once
#define SKYLIGHT_XPC_SERVICE_NAME "$SKYLIGHT_XPC_SERVICE"
#define SKYLIGHT_HOST_EXECUTABLE_RELATIVE_PATH "$SKYLIGHT_HOST_EXECUTABLE_RELATIVE_PATH"
#define SKYLIGHT_LAUNCH_AGENT_PLIST_NAME "$SKYLIGHT_LAUNCH_AGENT_PLIST_NAME"
#define SKYLIGHT_MENU_PEER_REQUIREMENT \\
  "$MENU_REQUIREMENT_CODE"
H

cat > "$SWIFT_OUTPUT" <<S
// GENERATED by macos-dist/generate-identity.sh -- do not edit, do not commit.
enum GeneratedIdentity {
    static let xpcServiceName = "$SKYLIGHT_XPC_SERVICE"
    static let hostExecutableRelativePath = "$SKYLIGHT_HOST_EXECUTABLE_RELATIVE_PATH"
    static let launchAgentPlistName = "$SKYLIGHT_LAUNCH_AGENT_PLIST_NAME"
    static let hostPeerRequirement =
        "$HOST_REQUIREMENT_CODE"
}
S

echo "generated identity: mode=$MODE bundle=$SKYLIGHT_BUNDLE_ID $IDENTITY_NOTE"
